#!/usr/bin/env node
// scripts/generate-seo-files.js
// Version: 1.0.0 | Date: 2024-12-18
// Generates sitemap.xml and robots.txt for static export builds
// Called after Next.js build completes

const fs = require('fs');
const path = require('path');

const mode = process.env.BUILD_MODE || 'local';

// Determine output directory based on build mode
const distDirs = {
  test: 'out-test',
  prod: 'out-prod',
  local: 'out'
};

const distDir = distDirs[mode];
const outputPath = path.join(__dirname, '..', distDir);

console.log(`\n🔍 Generating SEO files for ${mode.toUpperCase()} mode`);
console.log(`📂 Output directory: ${outputPath}\n`);

if (!fs.existsSync(outputPath)) {
  console.error(`❌ Error: Output directory does not exist: ${outputPath}`);
  console.error(`   Run the build first: npm run build:${mode}\n`);
  process.exit(1);
}

// --- Load navigation config ---
const navConfigPath = path.join(__dirname, '..', 'lib', 'navigation.ts');
let navItems = [];

try {
  const navContent = fs.readFileSync(navConfigPath, 'utf8');
  
  // Extract navItems array from TypeScript file (simple regex extraction)
  const navItemsMatch = navContent.match(/export const navItems.*?=\s*\[([\s\S]*?)\]/);
  
  if (navItemsMatch) {
    // Parse the array content (crude but works for simple objects)
    const arrayContent = navItemsMatch[1];
    const itemMatches = arrayContent.matchAll(/\{[^}]+\}/g);
    
    for (const match of itemMatches) {
      const itemStr = match[0];
      const href = itemStr.match(/href:\s*['"]([^'"]+)['"]/)?.[1];
      const priority = itemStr.match(/priority:\s*([\d.]+)/)?.[1];
      const changeFreq = itemStr.match(/changeFrequency:\s*['"]([^'"]+)['"]/)?.[1];
      
      if (href) {
        navItems.push({
          href,
          priority: priority ? parseFloat(priority) : 0.5,
          changeFrequency: changeFreq || 'monthly'
        });
      }
    }
  }
  
  console.log(`✅ Loaded ${navItems.length} navigation items from config`);
} catch (err) {
  console.error('⚠️  Could not load navigation config, using defaults');
  navItems = [
    { href: '/', priority: 1, changeFrequency: 'daily' },
    { href: '/products', priority: 0.9, changeFrequency: 'weekly' },
    { href: '/about', priority: 0.7, changeFrequency: 'monthly' },
    { href: '/contact', priority: 0.6, changeFrequency: 'monthly' },
    { href: '/faq', priority: 0.6, changeFrequency: 'monthly' },
  ];
}

// --- Load products data ---
const productsPath = path.join(__dirname, '..', 'public', 'data', 'final-products.json');
let products = [];

try {
  const productsData = fs.readFileSync(productsPath, 'utf8');
  products = JSON.parse(productsData);
  console.log(`✅ Loaded ${products.length} products from JSON\n`);
} catch (err) {
  console.error('⚠️  Could not load products data:', err.message);
  console.error('   Sitemap will only include static pages\n');
}

// --- Generate sitemap.xml ---
const baseUrl = mode === 'test' 
  ? 'https://crystalkeepsakes.com/test'
  : 'https://crystalkeepsakes.com';

const now = new Date().toISOString();

let sitemapXml = '<?xml version="1.0" encoding="UTF-8"?>\n';
sitemapXml += '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n';

// Add static pages from navigation
navItems.forEach(item => {
  sitemapXml += '  <url>\n';
  sitemapXml += `    <loc>${baseUrl}${item.href}</loc>\n`;
  sitemapXml += `    <lastmod>${now}</lastmod>\n`;
  sitemapXml += `    <changefreq>${item.changeFrequency}</changefreq>\n`;
  sitemapXml += `    <priority>${item.priority}</priority>\n`;
  sitemapXml += '  </url>\n';
});

// Add product pages
products.forEach(product => {
  if (product.slug) {
    sitemapXml += '  <url>\n';
    sitemapXml += `    <loc>${baseUrl}/products/${product.slug}</loc>\n`;
    sitemapXml += `    <lastmod>${now}</lastmod>\n`;
    sitemapXml += `    <changefreq>weekly</changefreq>\n`;
    sitemapXml += `    <priority>0.8</priority>\n`;
    sitemapXml += '  </url>\n';
  }
});

sitemapXml += '</urlset>\n';

// Write sitemap.xml
const sitemapPath = path.join(outputPath, 'sitemap.xml');
fs.writeFileSync(sitemapPath, sitemapXml, 'utf8');
console.log(`✅ Generated sitemap.xml with ${navItems.length + products.length} URLs`);
console.log(`   📄 ${sitemapPath}\n`);

// --- Generate robots.txt ---
let robotsTxt = '# robots.txt\n';
robotsTxt += '# Generated by CrystalKeepsakes build system\n\n';
robotsTxt += 'User-agent: *\n';
robotsTxt += 'Allow: /\n';
robotsTxt += 'Disallow: /api/\n';
robotsTxt += 'Disallow: /admin/\n';
robotsTxt += 'Disallow: /_next/\n';
robotsTxt += 'Disallow: /private/\n\n';

const sitemapUrl = mode === 'test'
  ? 'https://crystalkeepsakes.com/test/sitemap.xml'
  : 'https://crystalkeepsakes.com/sitemap.xml';

robotsTxt += `Sitemap: ${sitemapUrl}\n`;

// Write robots.txt
const robotsPath = path.join(outputPath, 'robots.txt');
fs.writeFileSync(robotsPath, robotsTxt, 'utf8');
console.log(`✅ Generated robots.txt`);
console.log(`   📄 ${robotsPath}\n`);

console.log('╔═══════════════════════════════════════════════════╗');
console.log('║         SEO FILES GENERATED SUCCESSFULLY          ║');
console.log('╠═══════════════════════════════════════════════════╣');
console.log(`║ sitemap.xml:  ${(navItems.length + products.length + ' URLs').padEnd(33)} ║`);
console.log(`║ robots.txt:   ✅${' '.repeat(32)}║`);
console.log('╚═══════════════════════════════════════════════════╝\n');