// One-time script to set all "Wooden Premium Base Mini" options to $45
// Run with: node scripts/fix-wooden-base-pricing.js

const fs = require('fs');
const path = require('path');

const filePath = path.join(__dirname, '../src/data/final-product-list.js');

// Read the file
let content = fs.readFileSync(filePath, 'utf-8');

// Parse the JavaScript module to get the array
const match = content.match(/export const finalProductList = (\[[\s\S]*?\]);/);
if (!match) {
  console.error('❌ Could not find finalProductList in file');
  process.exit(1);
}

const productsJSON = match[1];
const products = eval(productsJSON); // Safe here since it's our own file

let updatedCount = 0;

// Update all "Wooden Premium Base Mini" prices to $45
products.forEach(product => {
  // Check lightBases
  if (product.lightBases && Array.isArray(product.lightBases)) {
    product.lightBases.forEach(base => {
      if (base.name === "Wooden Premium Base Mini") {
        if (base.price !== 45) {
          console.log(`📝 Product "${product.name}" - Setting Wooden Base to $45 (was: ${base.price})`);
          base.price = 45;
          updatedCount++;
        }
      }
    });
  }
});

// Generate the new file content
const newContent = `// Final product list - Generated by admin panel or cockpit3d-products
// This is the SINGLE SOURCE OF TRUTH for all products on the site

export const finalProductList = ${JSON.stringify(products, null, 2)};

export default finalProductList;
`;

// Write back to file
fs.writeFileSync(filePath, newContent, 'utf-8');

console.log(`\n✅ Updated ${updatedCount} instances of "Wooden Premium Base Mini" to $45`);
console.log('📁 File updated: src/data/final-product-list.js');
console.log('\n💡 You can now adjust individual prices in the admin panel!');
